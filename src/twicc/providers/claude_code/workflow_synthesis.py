"""Synthesize a workflow run's "running view" (STATE 1) while it is still live.

A running workflow only records its phase→agent mapping at completion (in the
final ``wf_*.json``). To show a run *in progress* we reconstruct that mapping
from three sources, none of which is the agents' raw JSONL (the watcher already
owns their ingestion):

  - the run's live ``journal.jsonl`` — which agents started / returned, and the
    schema ``result`` each returned;
  - each agent's prompt — its workflow-subagent's first user message, already in
    the DB under the composite id ``<run_id>:<agent_id>``;
  - ``templates`` — ``[{phase, segments}]`` generated by a viewing front from the
    launch script (stored in ``Workflow.synthesis``).

:func:`detect_phase` matches a prompt against the templates; :func:`build_state1`
assembles the **common view format** (mirrors the ``wf_*.json`` envelope, marked
``synthetic``) so the front renders a running run and a finished one identically.

Pure Python, DB-driven, no eval — the template *generation* (eval of the script)
happens in the browser; only this string-matching half runs on the back.
"""
from __future__ import annotations

import logging
import re

import orjson

from twicc.core.enums import Provider

from .helpers import ClaudeCodeHelpers

logger = logging.getLogger(__name__)

_WS_RE = re.compile(r"\s+")


def _norm(text: str) -> str:
    """Collapse runs of whitespace to single spaces and trim (matches the
    template generator's ``norm`` so segments compare on equal footing)."""
    return _WS_RE.sub(" ", text).strip()


def detect_phase(prompt: str, templates: list[dict]) -> str | None:
    """Best-matching phase title for ``prompt`` among ``templates``, or ``None``.

    Faithful port of the playground's Script B: a template is a candidate when at
    least half its (already whitespace-normalized) static segments appear as
    substrings of the normalized prompt; among candidates the one matching the
    most total text wins. Different phases carry distinct instruction blocks, so
    cross-phase confusion does not happen. The "half" tolerance absorbs a baked
    enum the live agent lacks, or a truncated first message.
    """
    normalized = _norm(prompt)
    best_phase: str | None = None
    best_score = -1
    for tpl in templates:
        segments = tpl.get("segments") or []
        if not segments:
            continue
        present = [seg for seg in segments if seg in normalized]
        if len(present) >= max(1, len(segments) // 2):
            score = sum(len(seg) for seg in present)
            if score > best_score:
                best_score = score
                best_phase = tpl.get("phase")
    return best_phase


def _journal_path(project_id: str, session_id: str, run_id: str):
    """Path of a run's live resume journal (read-only; the watcher owns writes)."""
    return (
        ClaudeCodeHelpers.PROJECTS_DIR
        / project_id
        / session_id
        / "subagents"
        / "workflows"
        / run_id
        / "journal.jsonl"
    )


def _script_start_time_ms(project_id: str, session_id: str, run_id: str) -> int | None:
    """Best-effort launch time of a live run: the mtime of its launch script.

    The engine writes ``workflows/scripts/<name>-<run_id>.js`` once, at launch, so
    its mtime is a stable proxy for "when the run started" — the only such signal
    available while a run is in flight (the journal carries no timestamps, and
    OSes don't reliably expose a file's birth time). STATE 2 never uses this: a
    finished run reads ``startTime``/``durationMs`` straight from its wf_*.json.
    """
    scripts_dir = (
        ClaudeCodeHelpers.PROJECTS_DIR / project_id / session_id / "workflows" / "scripts"
    )
    try:
        matches = sorted(scripts_dir.glob(f"*-{run_id}.js"))
    except OSError:
        return None
    for path in matches:
        try:
            return int(path.stat().st_mtime * 1000)
        except OSError:
            continue
    return None


def _read_journal(project_id: str, session_id: str, run_id: str) -> list[dict]:
    """Parse the run journal into ``{type, key, agentId, result?}`` events.

    Missing file → ``[]`` (the run may not have spawned an agent yet). A partial
    last line caught mid-write fails to parse and is skipped, like the wf_*.json
    upsert path.
    """
    path = _journal_path(project_id, session_id, run_id)
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError:
        return []
    events: list[dict] = []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            events.append(orjson.loads(line))
        except orjson.JSONDecodeError:
            continue
    return events


def _agent_sessions(run_id: str) -> dict[str, dict]:
    """Per-agent Session metadata for a run, keyed by agent_id.

    Workflow agents are Sessions keyed ``<run_id>:<agent_id>`` (already synced by
    the watcher). We surface the few fields the real wf_*.json carries that the
    journal lacks — model + timing — so the synthetic STATE 1 envelope mirrors it.
    """
    from twicc.core.models import Session

    prefix = f"{run_id}:"
    rows = Session.objects.filter(id__startswith=prefix).values(
        "id", "model", "last_started_at", "last_updated_at"
    )
    return {r["id"][len(prefix):]: r for r in rows}


def _to_ms(dt) -> int | None:
    """Aware datetime → epoch milliseconds (matches the engine's startedAt/…)."""
    return int(dt.timestamp() * 1000) if dt is not None else None


def _launch_args(session_id: str, run_id: str):
    """The ``args`` passed to the Workflow tool that launched ``run_id``, or None.

    The final wf_*.json carries ``args``, but a still-running STATE 1 run has no
    such file yet — the args only live in the launching tool_use's input. Map
    run_id → tool_use_id via the tool_result's ``toolUseResult.runId`` (like
    :func:`views._derive_workflow_links`), then read that Workflow tool_use's
    ``input.args``. Read-only, from synced SessionItems (survives JSONL removal).
    Called once per run then cached in the envelope — never re-scanned each tick.
    """
    from twicc.core.models import SessionItem

    base = SessionItem.objects.filter(session_id=session_id).only("content")
    # 1) run_id → launching tool_use_id (from its tool_result).
    tool_use_id = None
    for it in base.filter(content__contains=run_id).iterator(chunk_size=20):
        try:
            parsed = orjson.loads(it.content)
        except orjson.JSONDecodeError:
            continue
        tur = parsed.get("toolUseResult")
        if not isinstance(tur, dict) or tur.get("runId") != run_id:
            continue
        content = (parsed.get("message") or {}).get("content")
        if isinstance(content, list):
            tool_use_id = next(
                (b.get("tool_use_id") for b in content
                 if isinstance(b, dict) and b.get("type") == "tool_result"),
                None,
            )
        if tool_use_id:
            break
    if not tool_use_id:
        return None
    # 2) tool_use_id → the Workflow tool_use's input.args.
    for it in base.filter(content__contains=tool_use_id).iterator(chunk_size=20):
        try:
            parsed = orjson.loads(it.content)
        except orjson.JSONDecodeError:
            continue
        content = (parsed.get("message") or {}).get("content")
        if not isinstance(content, list):
            continue
        for b in content:
            if (isinstance(b, dict) and b.get("type") == "tool_use"
                    and b.get("id") == tool_use_id and b.get("name") == "Workflow"):
                return (b.get("input") or {}).get("args")
    return None


def build_state1(
    run_id: str,
    project_id: str,
    session_id: str,
    synthesis: dict,
    script: str | None,
    prior_args=None,
) -> dict:
    """Assemble the STATE 1 (synthesized) view envelope for a live run.

    ``synthesis`` is ``{meta, templates}`` (front-supplied). Agents come from the
    journal, in start order; each is looked up in the DB for its prompt (first
    user message) → phase detection. An agent present in the journal but **not
    yet synced** to the DB is included with its journal state but no phase — it
    gets tagged on the next rebuild (the journal ticks every ~10-15s).

    ``prior_args`` is the args already resolved on an earlier rebuild (carried in
    the prior envelope) — passed back so the launching tool_use is scanned at most
    once per run, not every tick.
    """
    meta = synthesis.get("meta") or {}
    templates = synthesis.get("templates") or []
    phases = meta.get("phases") or []
    # phaseIndex is 1-based, mirroring the engine's wf_*.json (phases[0] → index 1):
    # the front matches agents to phases by title, but the synthetic envelope stays
    # a faithful mirror of the real one so both states share one shape.
    phase_index = {p.get("title"): i + 1 for i, p in enumerate(phases) if isinstance(p, dict)}

    # Aggregate journal events per agent, preserving first-seen (start) order.
    order: list[str] = []
    agents: dict[str, dict] = {}
    for event in _read_journal(project_id, session_id, run_id):
        agent_id = event.get("agentId")
        if not agent_id:
            continue
        if agent_id not in agents:
            agents[agent_id] = {"state": "running", "result": None}
            order.append(agent_id)
        if event.get("type") == "result":
            agents[agent_id]["state"] = "completed"
            agents[agent_id]["result"] = event.get("result")

    helpers = _get_helpers()
    agent_meta = _agent_sessions(run_id)
    progress: list[dict] = [
        {"type": "workflow_phase", "index": i + 1, "title": p.get("title")}
        for i, p in enumerate(phases)
        if isinstance(p, dict)
    ]
    for i, agent_id in enumerate(order):
        info = agents[agent_id]
        # ``index`` mirrors the engine's 1-based agent ordinal (= journal start
        # order). model/startedAt/lastProgressAt/durationMs come from the agent's
        # synced Session — the journal carries no timestamps. The rest of the real
        # envelope's agent fields (tokens, toolCalls, label, …) have no live source.
        entry: dict = {"type": "workflow_agent", "index": i + 1, "agentId": agent_id, "state": info["state"]}
        meta_row = agent_meta.get(agent_id)
        if meta_row:
            if meta_row.get("model"):
                entry["model"] = meta_row["model"]
            started_ms = _to_ms(meta_row.get("last_started_at"))
            progress_ms = _to_ms(meta_row.get("last_updated_at"))
            if started_ms is not None:
                entry["startedAt"] = started_ms
            if progress_ms is not None:
                entry["lastProgressAt"] = progress_ms
            if started_ms is not None and progress_ms is not None:
                entry["durationMs"] = max(0, progress_ms - started_ms)
        prompt = helpers.get_first_user_message(f"{run_id}:{agent_id}")
        if prompt is not None:
            # Full prompt, not a preview: we have it (the agent's first user
            # message) and storing it whole is durable past Claude deleting the
            # run's files. The engine's "Preview" naming is just a CLI display cap.
            entry["promptPreview"] = prompt
            phase_title = detect_phase(prompt, templates)
            if phase_title is not None:
                entry["phaseTitle"] = phase_title
                if phase_title in phase_index:
                    entry["phaseIndex"] = phase_index[phase_title]
        if info["result"] is not None:
            # Full result as its structured value (not stringified/truncated), so
            # the front renders a clean JsonHumanView.
            entry["resultPreview"] = info["result"]
        progress.append(entry)

    # Args live only in the launching tool_use until the final wf_*.json — recover
    # them once (reusing a value already found on a prior rebuild). STATE 2 carries
    # its own args verbatim.
    args = prior_args if prior_args is not None else _launch_args(session_id, run_id)

    return {
        "synthetic": True,
        "status": "pending",
        "runId": run_id,
        "workflowName": meta.get("name"),
        "summary": meta.get("description"),
        "args": args,
        # Launch time (script mtime) so the front can show a start time + a live
        # duration for a run still in flight. STATE 2 overwrites this with the
        # wf_*.json's own startTime/durationMs.
        "startTime": _script_start_time_ms(project_id, session_id, run_id),
        "phases": phases,
        "script": script,
        "agentCount": len(order),
        "workflowProgress": progress,
    }


def rebuild_state1(run_id: str) -> dict | None:
    """Rebuild a run's STATE 1 ``raw_json`` from its stored synthesis + live
    journal, persist it, and return the new envelope dict.

    Returns ``None`` (no write) when the run is not in a synthesizable state:
    no row, no ``synthesis`` yet (no front has generated templates), or the real
    envelope already landed (STATE 2 — never regress a completed run). Sync;
    wrap in ``sync_to_async`` at the call site.
    """
    from twicc.core.models import Workflow

    try:
        workflow = Workflow.objects.select_related("session").get(run_id=run_id)
    except Workflow.DoesNotExist:
        return None
    if not workflow.synthesis:
        return None
    try:
        prior = orjson.loads(workflow.raw_json)
    except orjson.JSONDecodeError:
        prior = {}
    if not prior.get("synthetic"):
        return None  # STATE 2 already

    envelope = build_state1(
        run_id,
        workflow.session.project_id,
        workflow.session_id,
        workflow.synthesis,
        prior.get("script"),
        prior.get("args"),
    )
    workflow.cost, workflow.phases_cost = Workflow.compute_costs(run_id, envelope)
    workflow.raw_json = orjson.dumps(envelope).decode()
    workflow.save(update_fields=["raw_json", "cost", "phases_cost", "updated_at"])
    return envelope


def enrich_previews(envelope: dict, project_id: str, session_id: str, run_id: str) -> dict:
    """Replace each agent's truncated promptPreview/resultPreview with the full
    prompt + result, mutating and returning ``envelope`` (STATE 2 ingestion).

    The engine truncates these for its own CLI display; we keep the full data,
    which is **durable past Claude's eventual deletion of the run's files** (the
    reason we mirror the envelope at all). Sources:
      - prompt ← the agent session's first user message (synced, persists in DB);
      - result ← the run journal's ``result`` event for the agent (present until
        the subagent files are sublimated).
    Each falls back to the envelope's own value when its source is unavailable.
    Sync; the caller wraps it (live watcher path / boot db-writer path).
    """
    progress = envelope.get("workflowProgress")
    if not isinstance(progress, list):
        return envelope
    agents = [e for e in progress if isinstance(e, dict) and e.get("type") == "workflow_agent"]
    if not agents:
        return envelope
    results = {
        event["agentId"]: event.get("result")
        for event in _read_journal(project_id, session_id, run_id)
        if event.get("type") == "result" and event.get("agentId")
    }
    helpers = _get_helpers()
    for entry in agents:
        agent_id = entry.get("agentId")
        if not agent_id:
            continue
        prompt = helpers.get_first_user_message(f"{run_id}:{agent_id}")
        if prompt is not None:
            entry["promptPreview"] = prompt
        if results.get(agent_id) is not None:
            entry["resultPreview"] = results[agent_id]
    return envelope


def _get_helpers():
    # Lazy: avoid importing the provider-helpers graph at module load (the
    # watcher and views import this module on a hot path).
    from twicc.providers.helpers import get_provider_helpers

    return get_provider_helpers(Provider.CLAUDE_CODE)
